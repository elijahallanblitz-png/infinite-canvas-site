// Packs public/ into src/static.gen.ts so the Worker serves its own files.
// Runs automatically before `wrangler dev` and `wrangler deploy` (see build.command in wrangler.jsonc).
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = 'public';
const TYPES = {
  html: 'text/html; charset=utf-8', css: 'text/css; charset=utf-8', js: 'text/javascript; charset=utf-8',
  png: 'image/png', webp: 'image/webp', woff2: 'font/woff2', svg: 'image/svg+xml', json: 'application/json', txt: 'text/plain; charset=utf-8',
};
const walk = (dir) => readdirSync(dir).flatMap((f) => { const p = join(dir, f); return statSync(p).isDirectory() ? walk(p) : [p]; });
const files = {};
for (const p of walk(ROOT).sort()) {
  const ext = p.split('.').pop();
  if (!TYPES[ext]) continue;
  const buf = readFileSync(p);
  files['/' + relative(ROOT, p).split('\\').join('/')] = [TYPES[ext], createHash('sha256').update(buf).digest('base64url').slice(0, 16), buf.toString('base64')];
}
const out = `// Generated by scripts/bundle-static.mjs. Do not edit.\nexport const FILES: Record<string, [type: string, etag: string, base64: string]> = ${JSON.stringify(files)};\n`;
let prev = '';
try { prev = readFileSync('src/static.gen.ts', 'utf8'); } catch { /* first run */ }
if (prev !== out) writeFileSync('src/static.gen.ts', out);
console.log(`bundled ${Object.keys(files).length} files, ${(out.length / 1024).toFixed(0)} KB`);
